import type { Ingredient, Meal, StoreSection, ColdChain, IngredientUnit } from '../types';

/**
 * Default meals.
 *
 * Written for family car camping on the BC coast, which means: the arrival
 * meal is trivial, at least two dinners survive rain, and the chili is frozen
 * flat so it doubles as the ice.
 */

type IngSpec = [
  name: string,
  amount: number,
  unit: IngredientUnit,
  section: StoreSection,
  cold?: ColdChain,
  extra?: Partial<Ingredient>,
];

const ing = (mealId: string) => (specs: IngSpec[]): Ingredient[] =>
  specs.map(([name, amount, unit, section, cold = 'ambient', extra = {}]) => ({
    id: `${mealId}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    name,
    amount,
    unit,
    scaling: 'per-eater',
    section,
    cold,
    ...extra,
  }));

